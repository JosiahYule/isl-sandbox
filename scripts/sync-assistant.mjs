// Copies the job assistant files from assistant/ into public/assistant/ so the site can serve them.
// Runs automatically before `npm run dev` and `npm run build` (see package.json).
// Edit the originals in assistant/, never the copies in public/assistant/.
import { mkdirSync, copyFileSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';

const out = 'public/assistant';

// The team directory the assistant uses for "who's in charge of marketing?" and "how do I reach Chance?".
// It's written from the website's own team data (src/data/team.js and bios.js), so the two never disagree.
// The generated file is committed, because the Supabase backend imports it too.
{
  const { bios } = await import('../src/data/bios.js');
  const teamSrc = readFileSync('src/data/team.js', 'utf8');
  const rows = [...teamSrc.matchAll(/\{ name: '([^']+)', slug: '([^']+)'.*?photo: cdn\('([^']+)'\)/g)];
  const directory = rows.map(([, name, slug, photo]) => {
    const b = bios[slug] || {};
    return { slug, name, first: name.split(' ')[0], title: b.title || '', province: b.province || '', email: b.email || '', phone: b.phone || '',
      photo: `https://images.squarespace-cdn.com/content/v1/691490c94119776708e69bbe/${photo}?format=300w` };
  });
  if (directory.length < 10) throw new Error('sync-assistant: could not read the team from src/data/team.js');
  let text = '// GENERATED by scripts/sync-assistant.mjs from src/data/team.js, bios.js, team-as.js and team-ads.js. Do not edit by hand:\n'
    + '// change the team data there and run `npm run sync-assistant`.\n'
    + 'export const DIRECTORY = ' + JSON.stringify(directory, null, 1) + ';\n';
  // Accountant Staffing's team (src/data/team-as.js), for the AS chatbot. Names without designations
  // ("Troy Yeo, CPA, CA" -> "Troy Yeo") so "how do I reach Troy Yeo?" finds him.
  // Administrative Staffing's team (team-ads.js) the same way.
  const { asTeam } = await import('../src/data/team-as.js');
  const { adsTeam } = await import('../src/data/team-ads.js');
  const toDirectory = (people) => people.map((p) => {
    const name = p.name.split(',')[0].trim();
    return { slug: p.slug, name, first: name.split(' ')[0], title: p.role, province: p.province, email: p.email, phone: p.phone, photo: p.photo + '?format=300w' };
  });
  text += 'export const DIRECTORY_AS = ' + JSON.stringify(toDirectory(asTeam), null, 1) + ';\n';
  text += 'export const DIRECTORY_ADS = ' + JSON.stringify(toDirectory(adsTeam), null, 1) + ';\n';
  const target = 'assistant/supabase/functions/_shared/directory.js';
  let before = '';
  try { before = readFileSync(target, 'utf8'); } catch {}
  if (before !== text) writeFileSync(target, text);
}
// Minimum wages and the Labour Force Survey, for the chat's answers ("what's minimum wage in PEI?",
// "is it hard to hire in Moncton?"). Written from the same files the Pay tool and the Atlantic jobs
// report use, so the chat never quotes a different number. Committed, like directory.js, because the
// Supabase backend imports it too; the jobs report workflow refreshes it when new figures arrive.
{
  const { MIN_WAGE, MIN_WAGE_CHECKED } = await import('../src/lib/minwage.js');
  let lfs = null;
  try { lfs = JSON.parse(readFileSync('src/data/lfs/latest.json', 'utf8')); } catch {}
  const market = { minWage: MIN_WAGE, minWageChecked: MIN_WAGE_CHECKED, month: null, released: null, geos: {}, industries: {} };
  if (lfs) {
    const at = (s, m) => s?.find((p) => p.month === m)?.value ?? null;
    const back = (m, n) => { const [y, x] = m.split('-').map(Number); return new Date(Date.UTC(y, x - 1 - n, 1)).toISOString().slice(0, 7); };
    const now = lfs.month, year = back(now, 12);
    const pair = (s) => (at(s, now) == null ? null : { now: at(s, now), year: at(s, year) });
    market.month = now;
    market.released = String(lfs.released || '').slice(0, 10);
    for (const g of ['NS', 'NB', 'PE', 'NL', 'CA']) {
      const p = lfs.provinces?.[g];
      if (!p) continue;
      market.geos[g] = { unemployment: pair(p.unemploymentRate), employment: pair(p.employment), wage: pair(lfs.wages?.[g]?.averageHourly), youth: pair(p.youthUnemploymentRate) };
      if (g !== 'CA') market.industries[g] = Object.fromEntries(Object.entries(lfs.industries?.[g] || {}).filter(([k]) => k !== 'Total').map(([k, s]) => [k, pair(s)]).filter(([, v]) => v));
    }
    // The four provinces together: unemployment from the people in the labour force and the people working
    const sum = (key, m) => ['NS', 'NB', 'PE', 'NL'].reduce((t, g) => t + (at(lfs.provinces[g]?.[key], m) ?? NaN), 0);
    const rateAt = (m) => Math.round((1 - sum('employment', m) / sum('labourForce', m)) * 1000) / 10;
    if (!Number.isNaN(rateAt(now))) market.geos.ATL = { unemployment: { now: rateAt(now), year: rateAt(year) }, employment: { now: sum('employment', now), year: sum('employment', year) } };
  }
  const text = '// GENERATED by scripts/sync-assistant.mjs from src/lib/minwage.js and src/data/lfs/latest.json. Do not edit by hand.\n'
    + 'export const MARKET = ' + JSON.stringify(market) + ';\n';
  const target = 'assistant/supabase/functions/_shared/market-data.js';
  let before = '';
  try { before = readFileSync(target, 'utf8'); } catch {}
  if (before !== text) writeFileSync(target, text);
}
const files = [
  ['assistant/supabase/functions/_shared/market.js', 'market.js'],
  ['assistant/supabase/functions/_shared/market-data.js', 'market-data.js'],
  ['assistant/widget/widget.js', 'widget.js'],
  ['assistant/supabase/functions/_shared/jobs.js', 'jobs.js'],
  ['assistant/supabase/functions/_shared/compensation.js', 'compensation.js'],
  ['assistant/supabase/functions/_shared/routing.js', 'routing.js'],
  ['assistant/supabase/functions/_shared/directory.js', 'directory.js'],
  ['assistant/supabase/functions/_shared/insights.js', 'insights.js'],
  ['assistant/supabase/functions/_shared/pay.js', 'pay.js'],
  ['assistant/supabase/functions/_shared/payroll.js', 'payroll.js'],
  ['assistant/supabase/functions/_shared/jobtext.js', 'jobtext.js'],
  ['assistant/demo-engine.js', 'demo-engine.js'],
  ['assistant/demo-mode.js', 'demo-mode.js'],
  ['assistant/data/jobs-snapshot.json', 'jobs-snapshot.json'],
  // Accountant Staffing and Administrative Staffing: their saved sample postings (src/data/jobs.js reads the same files)
  ['src/brands/jobs/as.json', 'jobs-as.json'],
  ['src/brands/jobs/ads.json', 'jobs-ads.json'],
];
const hash = createHash('sha256');
for (const [from] of files) hash.update(readFileSync(from));
const version = hash.digest('hex').slice(0, 12);
// This folder contains only generated copies, never the editable assistant sources.
rmSync(out, { recursive: true, force: true });
mkdirSync(`${out}/${version}`, { recursive: true });
for (const [from, to] of files) {
  copyFileSync(from, `${out}/${to}`); // stable local paths for the existing assistant tests/demo
  copyFileSync(from, `${out}/${version}/${to}`);
}
writeFileSync(`${out}/version.json`, JSON.stringify({ version }));
console.log(`Copied ${files.length} job assistant files to ${out}/${version}/`);
